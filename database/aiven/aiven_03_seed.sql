--    Non-bedrooms have capacity 0, so they get no beds.
--    (Read from a temporary copy of the rooms, for the trigger reason above.)
CREATE TEMPORARY TABLE new_rooms (room_id VARCHAR(10) COLLATE utf8mb4_general_ci NOT NULL PRIMARY KEY, capacity INT NOT NULL);
INSERT INTO new_rooms
  SELECT r.room_id, r.capacity FROM rooms r
  JOIN blocks b ON b.block_id = r.block_id
  WHERE b.hostel_id = 'H001' AND r.capacity > 0;
INSERT INTO beds (bed_id, room_id, bed_label, status)
SELECT CONCAT(r.room_id, '-', n.n), r.room_id, CONCAT('Bed ', CHAR(64 + n.n)), 'Available'
FROM new_rooms r
JOIN (SELECT 1 AS n UNION SELECT 2 UNION SELECT 3
      UNION SELECT 4 UNION SELECT 5 UNION SELECT 6) n
  ON n.n <= r.capacity;
DROP TEMPORARY TABLE new_rooms;

